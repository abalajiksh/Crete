#!/usr/bin/env python3
"""winget_manifest.py -- write the winget manifests for a crete release.

    scripts/winget_manifest.py TAG ZIP OUT_DIR

Writes OUT_DIR/manifests/a/abksh/crete/X.Y.Z/ with the three files a
microsoft/winget-pkgs pull request carries (version, installer, en-US
locale), for the Windows zip attached to TAG's Codeberg release. Submitting
is a separate, deliberate step -- see packaging/winget/README.md.

The package is the zip itself: InstallerType zip, both exes as portable
commands (`crete`, `crete-gui`). ArchiveBinariesDependOnPath puts the
extracted folder on PATH instead of symlinking the exes, because crete-gui
finds its fonts\\ beside its own executable (SDL_GetBasePath) and a symlinked
launch would look beside the link.

ZIP is checked the same way as scripts/bump_scoop_bucket.py checks it: tag
build name, and the exes where the manifest says they are.
"""

import hashlib
import re
import sys
import zipfile
from datetime import date
from pathlib import Path

ID = "abksh.crete"
SCHEMA = "1.10.0"
REPO = "https://codeberg.org/abksh/Crete"
ASSET = REPO + "/releases/download/v{v}/crete-{v}-windows-x86_64.zip"


def die(msg):
    sys.exit(f"winget_manifest: {msg}")


def header(kind):
    return (f"# yaml-language-server: $schema=https://aka.ms/winget-manifest.{kind}.{SCHEMA}.schema.json\n"
            "# Generated by scripts/winget_manifest.py in the crete repository.\n\n")


def main(argv):
    if len(argv) != 3:
        die("usage: winget_manifest.py TAG ZIP OUT_DIR")
    tag, zp, out = argv[0], Path(argv[1]), Path(argv[2])
    if not re.fullmatch(r"v\d+\.\d+\.\d+", tag):
        die(f"tag {tag!r} is not vX.Y.Z")
    v = tag[1:]
    top = f"crete-{v}-windows-x86_64"
    if zp.name != top + ".zip":
        die(f"{zp.name} is not {top}.zip -- only a tag build of Crete-Windows can be released")
    with zipfile.ZipFile(zp) as z:
        names = set(z.namelist())
    for exe in ("crete.exe", "crete-gui.exe"):
        if f"{top}/{exe}" not in names:
            die(f"{zp.name} has no {top}/{exe}")
    sha = hashlib.sha256(zp.read_bytes()).hexdigest().upper()

    d = out / "manifests" / "a" / "abksh" / "crete" / v
    d.mkdir(parents=True, exist_ok=True)
    common = f"PackageIdentifier: {ID}\nPackageVersion: {v}\n"

    (d / f"{ID}.yaml").write_text(
        header("version") + common +
        "DefaultLocale: en-US\n"
        f"ManifestType: version\nManifestVersion: {SCHEMA}\n", encoding="utf-8")

    (d / f"{ID}.installer.yaml").write_text(
        header("installer") + common +
        "InstallerType: zip\n"
        "NestedInstallerType: portable\n"
        "NestedInstallerFiles:\n"
        f"- RelativeFilePath: {top}\\crete.exe\n"
        "  PortableCommandAlias: crete\n"
        f"- RelativeFilePath: {top}\\crete-gui.exe\n"
        "  PortableCommandAlias: crete-gui\n"
        "ArchiveBinariesDependOnPath: true\n"
        f"ReleaseDate: {date.today().isoformat()}\n"
        "Installers:\n"
        "- Architecture: x64\n"
        f"  InstallerUrl: {ASSET.format(v=v)}\n"
        f"  InstallerSha256: {sha}\n"
        f"ManifestType: installer\nManifestVersion: {SCHEMA}\n", encoding="utf-8")

    (d / f"{ID}.locale.en-US.yaml").write_text(
        header("defaultLocale") + common +
        "PackageLocale: en-US\n"
        "Publisher: Ashwin Balaji\n"
        "PublisherUrl: https://codeberg.org/abksh\n"
        "PackageName: crête\n"
        f"PackageUrl: {REPO}\n"
        "License: MIT (FFmpeg LGPL-2.1-or-later, libdsddpcm BSD-2-Clause, SDL2 Zlib, fonts OFL-1.1)\n"
        f"LicenseUrl: {REPO}/src/branch/main/LICENSE\n"
        "ShortDescription: Dynamic-range and loudness meter (TT DR, EBU R128, true peak)\n"
        "Description: |-\n"
        "  crête measures TT Dynamic Range (dr.loudness-war.info), EBU R128 loudness and LRA,\n"
        "  true peak, PLR/PSR and crest factor, per channel, for stereo, quad, 5.1 and 7.1.\n"
        "  Reads WAV/RF64/AIFF/FLAC/DSF/DFF, SACD ISO images, cue sheets, DVD title sets and,\n"
        "  through a built-in LGPL FFmpeg, ALAC, AAC, MP3, TrueHD, DTS-HD MA and AC-3/E-AC-3.\n"
        "  Installs two commands: crete (command line) and crete-gui.\n"
        "Moniker: crete\n"
        "Tags:\n- audio\n- dynamic-range\n- loudness\n- ebu-r128\n- meter\n- dsd\n"
        f"ReleaseNotesUrl: {REPO}/releases/tag/{tag}\n"
        f"ManifestType: defaultLocale\nManifestVersion: {SCHEMA}\n", encoding="utf-8")

    for f in sorted(d.iterdir()):
        print(f)


if __name__ == "__main__":
    main(sys.argv[1:])
